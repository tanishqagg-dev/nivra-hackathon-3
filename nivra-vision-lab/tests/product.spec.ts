import { expect, test } from '@playwright/test'

test.describe('first run', () => {
  test.use({ storageState: { cookies: [], origins: [] } })

  test('opens setup, keeps progress, and finishes into the live view', async ({ page }) => {
    await page.goto('/')
    await expect(page).toHaveURL(/#\/setup$/)
    await expect(page.getByRole('heading', { name: 'Name the site' })).toBeVisible()
    const next = page.getByRole('button', { name: /^Continue/ })
    await expect(next).toBeDisabled()
    await page.getByLabel('Site name').fill('Main gate')
    await next.click()
    await expect(page.getByRole('heading', { name: 'Connect a camera' })).toBeVisible()
    // Progress survives a reload.
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Connect a camera' })).toBeVisible()
    await page.getByRole('button', { name: /Test scenario/ }).click()
    await expect(page.getByRole('button', { name: /^Continue/ })).toBeEnabled({ timeout: 10_000 })
    await page.getByRole('button', { name: /^Continue/ }).click()
    await page.getByRole('button', { name: 'Skip for now' }).click()
    await page.getByRole('button', { name: 'Skip for now' }).click()
    await page.getByRole('button', { name: /^Open the console/ }).click()
    await expect(page).toHaveURL(/#\/console$/)
    await expect(page.getByTestId('camera-status')).toHaveText('Test scenario')
    await expect(page.locator('.topbar-site')).toHaveText('Main gate')
  })
})

test('pages keep the camera running behind them', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Test scenario', exact: true }).click()
  await expect(page.getByTestId('camera-status')).toHaveText('Test scenario')
  await page.getByRole('group', { name: 'Pages' }).getByRole('button', { name: 'Settings' }).click()
  await expect(page).toHaveURL(/#\/settings$/)
  await expect(page.getByRole('heading', { name: 'Site', exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: 'Settings sections' }).getByRole('button', { name: 'Detection' }).click()
  await expect(page.getByLabel('Detection sensitivity')).toBeVisible()
  await page.getByRole('group', { name: 'Pages' }).getByRole('button', { name: 'Live' }).click()
  await expect(page.getByTestId('camera-status')).toHaveText('Test scenario')
})

test('an alert saves an incident with a five second clip', async ({ page }) => {
  test.setTimeout(90_000)
  const health = await page.request.get('/api/fight/incidents').catch(() => null)
  test.skip(!health?.ok(), 'Incident store is not running behind the preview server.')
  await page.goto('/')
  await page.getByRole('button', { name: 'Test scenario', exact: true }).click()
  const alert = page.getByTestId('review-alert')
  await expect(alert).toBeVisible({ timeout: 30_000 })
  await expect(alert.locator('.clip-player video')).toHaveCount(1, { timeout: 20_000 })
  await alert.getByRole('button', { name: 'Acknowledge' }).click()
  await page.getByRole('group', { name: 'Pages' }).getByRole('button', { name: 'Incidents' }).click()
  const detail = page.getByRole('article', { name: 'Incident detail' })
  await expect(detail).toContainText('Possible physical conflict')
  await expect(detail).toContainText('Acknowledged on the Mac')
  await expect(detail.locator('video')).toHaveCount(1)
  // Rows deep-link to their incident.
  const row = page.getByRole('list', { name: 'Incidents' }).getByRole('button').first()
  await row.click()
  await expect(page).toHaveURL(/#\/incidents\/inc_/)
  await expect(row).toHaveAttribute('aria-current', 'true')
})

test('an added camera raises its own alert with its own name', async ({ page }) => {
  test.setTimeout(90_000)
  await page.goto('/')
  await page.getByRole('button', { name: /Add camera/ }).first().click()
  await page.getByLabel('Source for Camera 2').selectOption('demo')
  const tile = page.getByTestId('camera-tile')
  await expect(tile).toContainText('Test scenario')
  const alert = page.getByTestId('review-alert')
  await expect(alert).toBeVisible({ timeout: 30_000 })
  await expect(alert.locator('.alert-where')).toContainText('Camera 2')
  await expect(tile.locator('.camera-stage')).toHaveClass(/is-alerting/)
  // CAM-01 is off, so its tile does not claim the alert.
  await expect(page.locator('#camera-stage')).not.toHaveClass(/is-alerting/)
  await page.getByRole('button', { name: 'Remove Camera 2' }).click()
  await expect(tile).toHaveCount(0)
})
